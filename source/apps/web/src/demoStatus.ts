// Verified runtime facts for the INTERNAL DEMO profile, read from the backend's /health.
//
// The readiness UI (modelStatus.ts) answers "can I ask a question?". This module answers the
// different question the internal demo has to display: "which model is actually loaded, and what
// was actually indexed?". A configured model name is not an answer to that, so nothing here is
// derived from configuration — every field comes from the backend, which in turn measured it.
//
// Validation is deliberately narrow and tolerant: an older or non-demo backend simply has no demo
// fields, and the UI then shows nothing rather than inventing a status.

import { API_BASE_URL } from "./api";

export const DEMO_STATUS_TIMEOUT_MS = 10_000;
export const MAX_DEMO_STATUS_BYTES = 128 * 1024;

/** The prefix of the warning the API attaches to every INTERNAL DEMO answer.
 *
 * It is the one demo signal that does not depend on how this build was configured: it travels in
 * the answer itself, so the page can tell that it is talking to a demo API even when this build was
 * served without the demo flag.
 */
export const DEMO_ANSWER_WARNING_PREFIX = "Internal experimental prototype:";

/** The prefix of the warning the API attaches when the retrieved records define the concept but
 * carry no operating steps. The page uses it to tell that state from a fully supported answer, so a
 * definition is never presented as a complete how-to.
 */
export const DEMO_CONCEPT_ONLY_PREFIX = "Source scope:";

/** The marker inside the warning the API attaches when it withheld the model's answer because that
 * answer contained a figure the retrieved records do not support. The page must say the answer was
 * withheld, not let the source excerpt read as the model's answer. It is a marker rather than a
 * prefix because that warning opens with the demo prefix, like every other demo warning.
 */
export const DEMO_WITHHELD_MARKER = "withheld answer";

/** The marker inside the warning the API attaches when a request for operations met records that
 * define the concept and carry no steps. The reply is then the server's own statement of what its
 * sources cover, with no model text in it, and the page must say so rather than present it as a
 * concept explanation. A marker for the same reason as the withheld one.
 */
export const DEMO_NO_PROCEDURE_MARKER = "procedure not in sources";

/** Markers of the replies the server composes itself for an answer mode: a lesson hint (Hint 1
 * or Hint 2), one guided step, the end of a guided lesson, and a request for operations on several
 * topics of which only some have steps. Each travels inside a demo-prefixed warning. */
export const DEMO_LESSON_HINT_MARKER = "lesson hint";
export const DEMO_GUIDED_STEP_MARKER = "guided step";
export const DEMO_LAST_STEP_MARKER = "the last step";
export const DEMO_GUIDED_COMPLETE_MARKER = "guided steps complete";
export const DEMO_PARTIAL_STEPS_MARKER = "steps for some topics only";

/** Markers of the warnings that accompany a reply the model actually generated: the standing demo
 * warning, and the withheld-answer warning (the model ran; its text was not published). A grounded
 * reply without one of these is the server's own — a lesson hint, a guided step, a sources
 * statement — and proves nothing about the model. */
export const DEMO_MODEL_RAN_MARKERS = ["generated by the v1b demo candidate", "withheld answer"];

/** The internal-use notice the demo must always display. */
export const INTERNAL_DEMO_NOTICE =
  "Internal experimental prototype. Answers may be incorrect. " +
  "Check the displayed course sources before relying on an answer.";

export interface DemoModelIdentity {
  readonly baseModelId: string;
  readonly baseModelRevision: string;
  readonly adapterSha256: string;
  readonly adapterMerged: boolean;
  readonly inferenceOnly: boolean;
  readonly device: string;
}

export interface DemoCorpus {
  readonly version: string;
  readonly sha256: string;
  readonly records: number;
  readonly label: string;
}

export interface DemoStatus {
  readonly internalDemo: boolean;
  readonly retrievalState: string;
  readonly retrievalDetail: string;
  readonly corpus: DemoCorpus | null;
  readonly topK: number | null;
  readonly identity: DemoModelIdentity | null;
}

function str(value: unknown): string | null {
  return typeof value === "string" && value.length > 0 ? value : null;
}

function record(value: unknown): Record<string, unknown> | null {
  return typeof value === "object" && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

export function parseDemoStatus(data: unknown): DemoStatus {
  const body = record(data) ?? {};
  const profile = record(body.profile);
  const retrieval = record(body.retrieval) ?? {};
  const corpusBody = record(retrieval.corpus);
  const identityBody = record(body.model_identity);

  const corpus: DemoCorpus | null =
    corpusBody &&
    str(corpusBody.corpus_version) &&
    str(corpusBody.corpus_sha256) &&
    typeof corpusBody.records === "number"
      ? {
          version: String(corpusBody.corpus_version),
          sha256: String(corpusBody.corpus_sha256),
          records: corpusBody.records,
          label: str(corpusBody.label) ?? "",
        }
      : null;

  // An identity is only shown when the backend says it verified one: the flag is the backend's,
  // not this module's, and a missing or false flag means nothing is displayed.
  const identity: DemoModelIdentity | null =
    identityBody &&
    identityBody.verified === true &&
    str(identityBody.adapter_sha256_measured) &&
    str(identityBody.base_model_id)
      ? {
          baseModelId: String(identityBody.base_model_id),
          baseModelRevision: str(identityBody.base_model_revision) ?? "",
          adapterSha256: String(identityBody.adapter_sha256_measured),
          adapterMerged: identityBody.adapter_merged_into_base_weights === true,
          inferenceOnly: identityBody.inference_only === true,
          device: str(identityBody.device) ?? "",
        }
      : null;

  return {
    internalDemo: profile?.internal_demo_enabled === true,
    retrievalState: str(retrieval.state) ?? "unknown",
    retrievalDetail: str(retrieval.detail) ?? "",
    corpus,
    topK: typeof retrieval.top_k === "number" ? retrieval.top_k : null,
    identity,
  };
}

/** Whether this build opts into the INTERNAL DEMO additions.
 *
 * The API has its own opt-in (`INTERNAL_DEMO_ENABLED`); this is the UI's. Without it the app
 * behaves exactly as it did before the demo existed: no /health request for identity, and no
 * identity or retrieval line. Nothing about the demo is on by default.
 */
export function internalDemoUiEnabled(): boolean {
  return import.meta.env.VITE_INTERNAL_DEMO === "true";
}

export interface DemoStatusOptions {
  readonly baseUrl?: string;
  readonly signal?: AbortSignal;
  readonly timeoutMs?: number;
}

/** Fetch /health and parse only the demo fields. Returns null when it cannot be read. */
export async function fetchDemoStatus(
  options: DemoStatusOptions = {},
): Promise<DemoStatus | null> {
  const baseUrl = options.baseUrl ?? API_BASE_URL;
  const controller = new AbortController();
  const timeout = setTimeout(
    () => controller.abort(),
    options.timeoutMs ?? DEMO_STATUS_TIMEOUT_MS,
  );
  const onAbort = () => controller.abort();
  options.signal?.addEventListener("abort", onAbort);
  try {
    const response = await fetch(`${baseUrl}/health`, {
      method: "GET",
      signal: controller.signal,
      credentials: "omit",
      cache: "no-store",
      redirect: "error",
    });
    if (!response.ok) {
      return null;
    }
    // Refuse an oversized body by its declared length before buffering it, and keep the
    // post-decode check as the fallback for a response that declares nothing.
    const declared = Number(response.headers.get("content-length") ?? "");
    if (Number.isFinite(declared) && declared > MAX_DEMO_STATUS_BYTES) {
      return null;
    }
    const text = await response.text();
    if (text.length > MAX_DEMO_STATUS_BYTES) {
      return null;
    }
    return parseDemoStatus(JSON.parse(text));
  } catch {
    // A demo badge is never worth an error dialog: an unreachable or malformed /health simply
    // leaves the extra lines out, and the readiness UI still reports the real state.
    return null;
  } finally {
    clearTimeout(timeout);
    options.signal?.removeEventListener("abort", onAbort);
  }
}

/** A short, honest label for an adapter digest. Full digests belong in the record, not a badge. */
export function shortDigest(digest: string): string {
  return digest.length <= 12 ? digest : `${digest.slice(0, 12)}…`;
}
