#: The internal draft task whose shape is prose only (no model-selected citation IDs).
DEMO_DRAFT_TASK = "course_answer_demo_draft"
#: The line that attaches the server-selected markers to the model's prose. The markers are what the
#: public contract requires; the sentence says plainly what they are.
SOURCES_PREFIX = "Course sources shown to the model:"
#: Carried in every demo answer so a reader is never left to assume the answer was checked.
DEMO_WARNING = (
    "Internal experimental prototype: this answer was generated by the V1B demo candidate from the "
    "small experimental concept corpus and has not been checked for teaching accuracy."
)
#: Carried when retrieval returned nothing, in place of the generated-answer warning. The shared
#: prefix is what lets the page recognise a demo answer without depending on how the build was
#: configured. It names the gap for what it is — the demo's sources — and says nothing about the
#: model: whether a model ran is an implementation detail that belongs in the internal provenance
#: log (``model_called``), not in what a student reads.
DEMO_NOT_COVERED_WARNING = (
    "Internal experimental prototype: this demo's course sources do not cover this topic yet, so "
    "there is nothing to cite."
)
#: The answer body for that state. The shared insufficient-evidence text calls the evidence
#: "approved course evidence", which would be false about a corpus labelled experimental and not
#: formally admitted, so the demo states its own position and lists the topics it really does carry.
DEMO_NO_COVERAGE_TEXT = (
    "That's outside what I can help with in this demo, so I won't guess. I focus on SOLIDWORKS and "
    "CSWA topics, and my current sources cover these: {topics}."
)
#: Appended when the authorized tutorial corpus carries steps: a real how-to the student can ask.
DEMO_PROCEDURE_HINT = (
    "Step-by-step guidance is available for {topics}. For example, you can ask "
    "“How do I use {first}?”"
)
#: Carried on a grounded answer whose retrieved records define the concept but contain no steps.
#: Derived from the records, not from the wording of the question.
DEMO_CONCEPT_ONLY_WARNING = (
    "Source scope: the retrieved records define this concept. They contain no operating steps, no "
    "dialog or menu path, no parameter values and no face-selection rules, so this answer is a "
    "concept explanation and not a complete how-to. Anything beyond the shown excerpts is not "
    "supported by the demo's sources."
)
#: Its stable opening words, which the page uses to tell the concept-only state from the others.
CONCEPT_ONLY_PREFIX = "Source scope:"
#: Carried on a grounded answer whose retrieved records include authorized procedure steps. The
#: steps are quoted from the authorized lesson, so what they do not state is not in the sources;
#: the warning says so instead of leaving the student to assume an exact interface path exists.
#: True by construction for any verbatim tutorial record, whatever its content. A distinct prefix,
#: so the page never mistakes it for the concept-only state.
DEMO_PROCEDURE_SCOPE_WARNING = (
    "Procedure scope: these steps are quoted from the authorized lesson. Anything they do not "
    "state — such as a menu path, a button, a parameter value or which faces to pick — is not in "
    "the demo's sources."
)
PROCEDURE_SCOPE_PREFIX = "Procedure scope:"
#: The marker line of a reply the server composed from the retrieved records without a model: the
#: records were checked, not shown to a model, and the line must not say otherwise.
SOURCES_CHECKED_PREFIX = "Course sources checked:"
#: Carried when a request for operations met records that define the concept and carry no steps.
#: It opens with the demo prefix like every demo warning and carries the stable marker below, which
#: the page uses to tell this state from a concept explanation the model wrote.
DEMO_NO_PROCEDURE_MARKER = "procedure not in sources"
DEMO_NO_PROCEDURE_WARNING = (
    "Internal experimental prototype: procedure not in sources — the retrieved records define the "
    "concept and contain no operating steps, so no step-by-step answer was produced for this "
    "request. The reply is the demo's own statement of what its sources cover."
)
#: The reply itself. Every term in it is a retrieved record's own canonical term. It ends by
#: inviting a conceptual question, in words the conversation layer resolves as a follow-up — or,
#: in a hint mode, by quoting the concept definition itself, labelled as concept only.
_NO_PROCEDURE_BASE = (
    "The demo's sources explain what \u201c{term}\u201d means, but they don't provide verified "
    "steps for it. I can explain the concept, but I shouldn't guess the interface steps"
)
_NO_PROCEDURE_BASE_PLURAL = (
    "The demo's sources explain what {terms} mean, but they don't provide verified steps for "
    "them. I can explain the concepts, but I shouldn't guess the interface steps"
)
DEMO_NO_PROCEDURE_TEXT = _NO_PROCEDURE_BASE + " \u2014 ask what it is or what it is used for."
DEMO_NO_PROCEDURE_TEXT_PLURAL = (
    _NO_PROCEDURE_BASE_PLURAL + " \u2014 ask what each one is or what they are used for."
)
DEMO_CONCEPT_ONLY_LINE = "Concept only \u2014 {term}: {definition}"
#: The scope warning each coverage label carries; a label not listed here carries none.
_SCOPE_WARNINGS: dict[str, str] = {
    "concept_only": DEMO_CONCEPT_ONLY_WARNING,
    "procedure": DEMO_PROCEDURE_SCOPE_WARNING,
}
#: Any run of digits, with an internal decimal separator: a thickness, a dimension, a release year.
_NUMBER_RE = re.compile(r"\d+(?:[.,]\d+)*")
#: A measurement: a figure followed by a length or angle unit ("2 mm", "1.5 millimetres", "30°",
#: "a 360-degree turn"). "in" and a bare "m" are left out: "step 2 in the dialog" is not inches.
_MEASUREMENT_RE = re.compile(
    r"(\d+(?:[.,]\d+)*)\s*-?\s*"
    r"(?:mm|millimet(?:er|re)s?|cm|centimet(?:er|re)s?|inch(?:es)?|°|deg(?:ree)?s?)(?![a-z])",
    re.IGNORECASE,
)
#: A candidate list-formatting ordinal: a one- or two-digit integer at a line start or after a
#: space, followed immediately by "." or ")" and then whitespace. A decimal such as 2.00 cannot
#: match (the character after the dot is a digit, not whitespace), nor can a four-digit year.
_LIST_ORDINAL_CANDIDATE = re.compile(r"(?m)(?:^|(?<=\s))(\d{1,2})[.)](?=\s)")
#: The answer body when the model's prose carried a figure the retrieved records do not contain.
#: The figures themselves are deliberately NOT repeated here: naming them would put the invented
#: value on the page, which is what this path exists to prevent. The full generated text stays in
#: the sidecar's own request log for whoever is debugging the demo.
DEMO_UNSUPPORTED_FIGURE_TEXT = (
    "The sources available to this demo do not state the specific value this question asks for. "
    "The model produced an answer that introduced numeric values appearing nowhere in the records "
    "it was shown, so that answer was withheld rather than published.\n\nWhat the retrieved "
    "records do say is shown below as the source excerpt, unchanged and with nothing added."
)
#: Carried with it. It opens with the demo prefix like every other demo warning, because a withheld
#: answer is still a demo answer and the page must not fall back to calling it approved course
#: material, and it carries the stable marker below so the page can show that an answer was
#: withheld rather than merely absent.
DEMO_UNSUPPORTED_FIGURE_WARNING = (
    "Internal experimental prototype: withheld answer — the model's text contained numeric values "
    "that the retrieved records do not support, so the server did not publish it. No figure was "
    "invented on this page, and none was corrected into a different one either; the generated text "
    "was simply not shown."
)
#: The stable marker inside it, matched case-insensitively by the page.
UNSUPPORTED_FIGURE_MARKER = "withheld answer"
#: Carried when the generation stopped at the token cap, so a cut-off sentence is not read as a
#: finished answer. The text is kept, never silently repaired or regenerated.
TRUNCATED_WARNING = (
    "The model stopped at the generation token limit, so this answer is cut off and may be "
    "incomplete. It is shown as produced, not regenerated."
)
#: The public contract's ceiling for ``answer_text``; the composed answer must fit inside it.
PUBLIC_ANSWER_TEXT_LIMIT = 12000


class _RenderedRecord:
    """The minimal shape the frozen record renderer reads: an object with ``text``.

    ``render_record_block`` numbers the records and joins them, reading nothing but ``text``. Using
    this view keeps the demo from re-implementing the reviewed byte contract and keeps what the
    model sees equal to what was retrieved.
    """

    __slots__ = ("text",)

    def __init__(self, text: str) -> None:
        self.text = text


def demo_sources_line(citation_ids: Sequence[str]) -> str:
    """The markers for the retrieved records, in retrieval order."""
    markers = " ".join(f"[{citation_id}]" for citation_id in citation_ids)
    return f"{SOURCES_PREFIX} {markers}"


def compose_demo_answer_text(answer_text: str, citation_ids: Sequence[str]) -> str:
    """The model's prose, then the server's marker line."""
    return f"{str(answer_text).strip()}\n\n{demo_sources_line(citation_ids)}"


def screen_demo_prose(answer_text: str) -> str:
    """Return the model's prose, or refuse it as invalid model output.

    The server owns every citation marker in a demo answer, so the model's prose must carry none.
    A bracketed token in it — a canonical id, an unterminated bracket, a stray ``[1.5]`` — would
    otherwise be parsed together with the server's appended source line and fail the public
    contract's marker law, which is the server's own boundary and reports a 500. Screening it here
    keeps that failure classified where it belongs: the model produced output that failed
    validation (502). Ordinary bracketed prose that the marker law does not treat as a candidate is
    left alone.
    """
    try:
        markers = parse_citation_markers(answer_text)
    except CitationMarkerError:
        raise InvalidModelOutputError(
            "the demo draft carries marker-shaped text; the server owns the citations"
        ) from None
    if markers:
        raise InvalidModelOutputError(
            "the demo draft selected a citation of its own; the server owns the citations"
        )
    return answer_text


def list_formatting_spans(answer_text: str) -> set[tuple[int, int]]:
    """Character spans of digits that are list formatting rather than technical values.

    A number counts as formatting only as part of a real list: at least two candidate markers, the
    first of them 1, each one more than the last. "1. … 2. … 3. …" therefore reads as layout, on one
    line or several, with "." or ")" and with or without a bullet in front.

    A lone "2." does not qualify — "Set it to 2. Then click OK" must keep 2 as a value — and neither
    does a list that starts somewhere other than 1, nor one whose numbering repeats. Those stay
    values, which is the conservative direction: a figure is never let through as punctuation.
    """
    candidates = [
        (match.start(1), match.end(1), int(match.group(1)))
        for match in _LIST_ORDINAL_CANDIDATE.finditer(str(answer_text))
    ]
    if len(candidates) < 2:
        return set()
    values = [value for _, _, value in candidates]
    if values[0] != 1 or any(later - earlier != 1 for earlier, later in pairwise(values)):
        return set()
    return {(start, end) for start, end, _ in candidates}


def unsupported_figures(answer_text: str, record_texts: Sequence[str]) -> tuple[str, ...]:
    """Technical values in the model's prose that appear in none of the records it was shown.

    A deliberately narrow, byte-level check with no interpretation of meaning: every number in the
    prose must occur literally in the retrieved source text. This corpus states definitions and
    almost no figures, so an invented thickness, dimension or release year surfaces here, while a
    figure the model correctly repeats from a record does not.

    List formatting is excluded, so ordinary "1. / 2. / 3." layout never costs an answer
    (:func:`list_formatting_spans`). A decimal, a dimension or a version number cannot hide as a
    marker: the exclusion applies to specific character spans of an ascending 1, 2, 3 run, not to
    any digit that happens to sit near a dot.

    A measurement — a figure with a length or angle unit — is supported only by a measurement in
    the sources. A tutorial record numbers its steps, so "2" occurs in it as a step number, and a
    step reference ("Step 2: …") must still pass; "set the thickness to 2 mm" must not.

    **This is not a check of semantic correctness.** It says nothing about whether a sentence is
    true, and it cannot catch a spelled-out number ("two millimetres"), a bare number with no unit
    that happens to occur in a record, or an invented menu path, none of which can be decided
    without interpreting the text. Those remain disclosed risks, and the shown source excerpt is
    what a reader checks the answer against.
    """
    text = str(answer_text)
    supported: set[str] = set()
    measured: set[str] = set()
    for block in record_texts:
        supported.update(_NUMBER_RE.findall(str(block)))
        measured.update(match.group(1) for match in _MEASUREMENT_RE.finditer(str(block)))
    formatting = list_formatting_spans(text)
    measurements = {match.span(1) for match in _MEASUREMENT_RE.finditer(text)}
    unsupported: dict[str, None] = {}
    for match in _NUMBER_RE.finditer(text):
        span = (match.start(), match.end())
        if span in formatting:
            continue
        if match.group(0) not in (measured if span in measurements else supported):
            unsupported.setdefault(match.group(0), None)
    return tuple(unsupported)


def strip_server_source_line(answer_text: str) -> str:
    """Remove the server's own appended source line from a previous answer.

    A prior assistant turn is replayed to the model so a follow-up stays on topic, but that turn
    ends with the line THIS module appended: "Course sources shown to the model: [id] [id]". Replay
    it and the model imitates it, emitting a citation marker of its own — which the marker screen
    then rejects as invalid model output, observed live on the third turn of the tutor flow.

    The server owns every marker, so the model never needs to see one. Everything from that line
    onwards is cut; the model's own prose is left exactly as it was.
    """
    text = str(answer_text)
    cuts = [
        index for index in map(text.find, (SOURCES_PREFIX, SOURCES_CHECKED_PREFIX)) if index >= 0
    ]
    return text[: min(cuts)].rstrip() if cuts else text


def demo_user_turn(question_text: str, record_texts: Sequence[str]) -> str:
    """The frozen Stage-C user turn: the retrieved records, then the question, verbatim."""
    block = render_record_block([_RenderedRecord(text) for text in record_texts])
    return build_user_turn(block, question_text)


def demo_insufficient_evidence_answer(
    question: CourseQuestion,
    supported_topics: Sequence[str] = (),
    procedure_topics: Sequence[str] = (),
    guided_progress: GuidedProgress | None = None,
) -> CourseAnswer:
    """The demo's own not-covered answer: one statement, one warning, real topics.

    The shared refusal says "approved course evidence is insufficient" and adds its own
    teaching-assistant warning; in this profile that is two sentences about the same thing, one of
    which calls an experimental corpus approved. This replaces both with the demo's own position,
    and lists the corpus's actual canonical terms so a reader can see what it does carry. When the
    authorized tutorial corpus carries steps, it also names those topics as a how-to the student
    can ask for. Every topic is read from a corpus, never composed for the occasion.
    """
    topics = ", ".join(str(topic) for topic in supported_topics)
    body = (
        DEMO_NO_COVERAGE_TEXT.format(topics=topics)
        if topics
        else DEMO_NO_COVERAGE_TEXT.split(" I focus on")[0]
    )
    procedures = [str(topic) for topic in procedure_topics]
    if procedures:
        body += "\n\n" + DEMO_PROCEDURE_HINT.format(
            topics=", ".join(procedures), first=procedures[0]
        )
    return finalize_course_answer(
        question,
        answer_text=body,
        citations=[],
        warnings=[DEMO_NOT_COVERED_WARNING],
        guided_progress=guided_progress,
    )


def demo_procedure_unavailable_answer(
    question: CourseQuestion,
    evidence: Sequence[RetrievedEvidence],
    terms: Sequence[str],
    procedure_topics: Sequence[str] = (),
    concept_definitions: Sequence[tuple[str, str]] = (),
    guided_progress: GuidedProgress | None = None,
) -> CourseAnswer:
    """The reply to a request for operations whose retrieved records carry no steps. No model runs.

    A definition is not procedural evidence, and a model given a definition and asked for steps
    invents them. So the server answers itself, in one deterministic statement: what the sources
    explain, that they state no verified steps, and that it will not guess them. ``terms`` are the
    retrieved records' own canonical terms. The records stay cited, so the source identity is
    preserved and shown, and the marker line says the records were checked — not shown to a model.
    When the authorized tutorial corpus carries steps for another topic, the reply names it.
    """
    allowed_evidence = validated_evidence_map(evidence)
    names = [str(term) for term in terms]
    if not allowed_evidence or not names:
        raise InternalContractError()
    ordered_ids = list(allowed_evidence)
    definitions = [(str(term), str(text)) for term, text in concept_definitions if str(text)]
    quoted = [f"\u201c{name}\u201d" for name in names]
    plural_terms = ", ".join(quoted[:-1]) + " and " + quoted[-1]
    if definitions:
        # A hint mode may explain the available concept: the definition is quoted, labelled.
        body = (
            _NO_PROCEDURE_BASE.format(term=names[0])
            if len(names) == 1
            else _NO_PROCEDURE_BASE_PLURAL.format(terms=plural_terms)
        ) + "."
        body += "".join(
            "\n\n" + DEMO_CONCEPT_ONLY_LINE.format(term=term, definition=text)
            for term, text in definitions
        )
    elif len(names) == 1:
        body = DEMO_NO_PROCEDURE_TEXT.format(term=names[0])
    else:
        body = DEMO_NO_PROCEDURE_TEXT_PLURAL.format(terms=plural_terms)
    procedures = [str(topic) for topic in procedure_topics if str(topic) not in names]
    if procedures:
        body += "\n\n" + DEMO_PROCEDURE_HINT.format(
            topics=", ".join(procedures), first=procedures[0]
        )
    markers = " ".join(f"[{citation_id}]" for citation_id in ordered_ids)
    return finalize_course_answer(
        question,
        answer_text=f"{body}\n\n{SOURCES_CHECKED_PREFIX} {markers}",
        citations=[allowed_evidence[evidence_id].citation for evidence_id in ordered_ids],
        warnings=[DEMO_NO_PROCEDURE_WARNING],
        guided_progress=guided_progress,
    )


async def answer_course_question_demo(
    question: CourseQuestion,
    backend: ModelBackend,
    evidence: Sequence[RetrievedEvidence] = (),
    record_texts: Sequence[str] = (),
    coverage: str | None = None,
    supported_topics: Sequence[str] = (),
    history: Sequence[ConversationTurn] = (),
    procedure_topics: Sequence[str] = (),
    question_text: str | None = None,
    guided_progress: GuidedProgress | None = None,
) -> CourseAnswer:
    """Answer one demo question from the evidence that was actually retrieved, or refuse.

    ``history`` is the bounded conversation context, already trimmed by the conversation layer. It
    reaches the model as prior turns so a follow-up stays on topic; it is never used to retrieve.

    ``coverage`` is what the retrieved records can support, from the retrieval layer:
    ``concept_only`` adds a warning saying the records define the concept but carry no steps.
    ``supported_topics`` is used only when there is no evidence at all.

    ``evidence`` and ``record_texts`` are parallel: one retrieved record each, in retrieval order.
    A mismatch is a server defect and fails closed rather than sending the model a block that does
    not correspond to the citations the answer would carry.

    ``question_text`` is the model-facing question when it differs from the student's — the
    answer mode's instruction appended under the records (see teaching_modes). The published
    answer still echoes the student's own question.
    """
    require_course_capabilities(backend)

    allowed_evidence = validated_evidence_map(evidence)
    if not allowed_evidence:
        return demo_insufficient_evidence_answer(
            question, supported_topics, procedure_topics, guided_progress
        )
    if len(record_texts) != len(allowed_evidence):
        raise InternalContractError()

    ordered_ids = list(allowed_evidence)
    # The bounded history travels as ordinary prior turns; only the final user turn carries the
    # retrieved records, through the frozen Stage-C wrapper. The wrapper itself is untouched.
    messages = [
        ChatMessage(
            role=turn.role,
            text=(
                strip_server_source_line(turn.content) if turn.role == "assistant" else turn.content
            ),
        )
        for turn in history
        if (
            strip_server_source_line(turn.content) if turn.role == "assistant" else turn.content
        ).strip()
    ]
    messages.append(
        ChatMessage(
            role="user",
            text=demo_user_turn(question_text or question.question, record_texts),
        )
    )
    draft = await generate_validated(backend, task=DEMO_DRAFT_TASK, messages=messages)
    prose = screen_demo_prose(draft.answer_text)
    citations: list[Citation] = [
        allowed_evidence[evidence_id].citation for evidence_id in ordered_ids
    ]
    scope_warning = _SCOPE_WARNINGS.get(coverage or "")
    scope_warnings = [scope_warning] if scope_warning else []

    if unsupported_figures(prose, record_texts):
        # The model answered with a figure none of the retrieved records contains. Publishing it
        # with a caveat would still put an invented value on the page, so it is withheld and the
        # source excerpt stands on its own. The citations are kept: those records really were
        # retrieved and really were shown to the model.
        return finalize_course_answer(
            question,
            answer_text=compose_demo_answer_text(DEMO_UNSUPPORTED_FIGURE_TEXT, ordered_ids),
            citations=citations,
            warnings=[DEMO_UNSUPPORTED_FIGURE_WARNING, *scope_warnings],
            guided_progress=guided_progress,
        )

    answer_text = compose_demo_answer_text(prose, ordered_ids)
    if len(answer_text) > PUBLIC_ANSWER_TEXT_LIMIT:
        # The prose plus the server's source line does not fit the published field. That is the
        # model's output being unusable, not the server assembling an invalid contract.
        raise InvalidModelOutputError(
            "the demo draft is too long to publish with its source markers"
        )
    warnings = [DEMO_WARNING, *scope_warnings]
    if getattr(draft, "finish_reason", None) == "length":
        warnings.append(TRUNCATED_WARNING)
    return finalize_course_answer(
        question,
        answer_text=answer_text,
        citations=citations,
        warnings=warnings,
        guided_progress=guided_progress,
    )
