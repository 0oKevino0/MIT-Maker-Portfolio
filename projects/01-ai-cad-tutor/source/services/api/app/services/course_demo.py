"""Course answer assembly for the INTERNAL DEMO profile.

This is a separate path, used only when ``internal_demo_enabled`` is set. The default profile's
``answer_course_question`` is untouched: it still asks the model for a JSON draft in which the model
selects its own citation IDs.

The demo path differs in exactly two ways, and both are recorded in the demo configuration record:

1. **The user turn carries the retrieved reference records.** It is built with the frozen Stage-C
   wrapper from ``model_mvp/rag/context.py`` (byte contract from review 0151), whose own text tells
   the model to treat the records as reference data rather than as instructions. The evaluated
   configuration sent the bare question with no context at all, so this is a demo difference and
   not a claim about the evaluated model.
2. **The server selects the citations.** The tutor model returns prose; this module attaches the
   citations for the records that were actually retrieved and shown to it, and appends their
   markers so the public contract's marker rule holds. A demo answer therefore cannot cite a source
   the retriever did not return, and a citation never asserts that the answer is correct.

Everything else is the existing machinery: the same fail-closed capability gate, the same
server-owned ``Citation`` objects, the same strict public-contract validation, and the same
insufficient-evidence answer when retrieval returns nothing — with the demo's own reason attached,
because in that case no model ran at all.

Model text is screened before it is composed, so the existing error matrix still applies to it: a
draft that carries marker-shaped text, or that cannot fit the public answer field once the server's
source line is appended, is model output that failed validation (502) rather than a server contract
defect (500).

A third screen is specific to this profile: prose carrying a numeric value that appears in none of
the retrieved records is withheld rather than published. The corpus states definitions and almost no
figures, so an invented thickness, dimension or release year is exactly what this catches — checked
against the retrieved source bytes, never by interpreting what the model meant. Ordinary list
formatting ("1. 2. 3.") is excluded by span, so layout alone never costs an answer, while a decimal
or a version number cannot pass as a marker. The screen is not a check of semantic correctness.
"""

